"""The published benchmark, shipped with the package: per scenario, the fault schedule and every run's result.

The human test and the console's pipeline benchmark replay the 20 benchmark scenarios with the benchmark's
schedule and score, and compare with its results. Those live in benchmark_results/ (the repository only, ~300 MB);
this module condenses what the comparison needs into operaitor/data/benchmark_reference.json, so the Windows app,
the Docker image and a pip install compare against the same numbers.

Regenerate after a new benchmark run (tests/test_pipeline_bench.py checks the file is up to date):

    py -3 -m operaitor.benchmark.reference
"""
from __future__ import annotations

from functools import lru_cache
import json
from pathlib import Path

SHIPPED = Path(__file__).resolve().parent.parent / "data" / "benchmark_reference.json"
# Campaign config key (benchmark/profit_campaign.py) of each reference pipeline (agents/pipeline.py)
CONFIG_OF_PRESET = {"llm_lucky": "lucky", "llm_judge": "judge", "llm": "llmtwin", "llm_admit": "admit",
                    "llm_admit_nosim": "admit_nosim"}


def _int_keys(sched: dict) -> dict:
    return {int(k): v for k, v in sched.items()}


def repo_available() -> bool:
    from .profit_campaign import OUT
    return any((OUT / "open_models_v2").glob("*/profit_campaign.json"))


def _repo_schedule(sid: str) -> tuple[dict, float]:
    from .profit_campaign import BY_ID, RUNS, lift_schedule, window_for
    try:
        probe = json.loads((RUNS / f"{sid}_probe.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        probe = {"trip_min": None}
    sched = lift_schedule(BY_ID[sid], probe)
    return sched, window_for(sched)


def _repo_rows(sid: str) -> list[dict]:
    """No agents, then every model x configuration (protocol v2) for this scenario."""
    from .profit_campaign import MODE_LABEL, OUT
    short = {"lucky": "LLM, no validation", "judge": "LLM + judge", "llmtwin": "LLM + digital twin",
             "admit": "LLM + ADMIT (sim)", "admit_nosim": "LLM + ADMIT (no sim)"}
    rows: list[dict] = []
    for path in sorted((OUT / "open_models_v2").glob("*/profit_campaign.json")):
        try:
            camp = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        row = next((r for r in camp.get("rows", []) if r["id"] == sid), None)
        if row is None:
            continue
        if not rows:
            rows.append({"who": "No agents", "model": None, "config": "passive", "profit": row["passive_profit"],
                         "stopped": row.get("passive_trip_min") is not None, "stop_min": row.get("passive_trip_min")})
        model = path.parent.name
        for mode, c in row["configs"].items():
            rows.append({"who": f"{model} · {short.get(mode) or MODE_LABEL.get(mode, mode)}", "model": model, "config": mode,
                         "profit": c["profit"], "stopped": c.get("trip_min") is not None, "stop_min": c.get("trip_min")})
    return rows


def build() -> dict:
    """The reference data from the repository's benchmark results."""
    from .profit_campaign import SCENARIOS
    out = {}
    for s in SCENARIOS:
        sched, window = _repo_schedule(s["id"])
        out[s["id"]] = {"schedule": {str(k): v for k, v in sched.items()}, "window_min": window, "rows": _repo_rows(s["id"])}
    return {"about": "Published OperAItor benchmark (protocol v2): fault schedule and results per scenario. "
                     "Generated by operaitor/benchmark/reference.py from benchmark_results/.",
            "scenarios": out}


@lru_cache(maxsize=1)
def shipped() -> dict:
    try:
        return json.loads(SHIPPED.read_text(encoding="utf-8"))["scenarios"]
    except (OSError, ValueError, KeyError):
        return {}


def schedule(sid: str) -> tuple[dict, float]:
    """Onset / lift per fault and the scoring window: the repository's probe run, else the shipped copy."""
    if repo_available() or sid not in shipped():
        return _repo_schedule(sid)
    s = shipped()[sid]
    return _int_keys(s["schedule"]), float(s["window_min"])


def rows(sid: str) -> list[dict]:
    """The benchmark's results for this scenario: the repository's, else the shipped copy."""
    if repo_available():
        return _repo_rows(sid)
    return [dict(r) for r in shipped().get(sid, {}).get("rows", [])]


def write() -> Path:
    SHIPPED.write_text(json.dumps(build(), indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return SHIPPED


if __name__ == "__main__":
    print(f"wrote {write()}")
